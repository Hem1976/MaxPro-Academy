function playlistQuestion(
  index: number,
  question: string,
  explanation: string,
  correct: string,
  wrong: [string, string, string],
): { question: QuizQuestion; options: QuizOption[] } {
  const questionId = `66666666-6666-6666-6666-66666666690${index.toString(16)}`;
  const optionBase = 0x900 + (index - 1) * 4;
  const texts = [
    { option_text: correct, is_correct: true },
    ...wrong.map((option_text) => ({ option_text, is_correct: false })),
  ];
  const rotateBy = (index - 1) % texts.length;
  const rotated = [...texts.slice(rotateBy), ...texts.slice(0, rotateBy)];

  return {
    question: {
      id: questionId,
      quiz_id: PLAYLIST_QUIZ_ID,
      question,
      explanation,
      sort_order: index,
      created_at: TIMESTAMP,
    },
    options: rotated.map((option, optionIndex) => ({
      id: `77777777-7777-7777-7777-777777777${(optionBase + optionIndex + 1).toString(16)}`,
      question_id: questionId,
      option_text: option.option_text,
      is_correct: option.is_correct,
      sort_order: optionIndex + 1,
    })),
  };
}

